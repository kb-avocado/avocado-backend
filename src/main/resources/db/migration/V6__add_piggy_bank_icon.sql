-- ============================================================
-- 저금통 대표 아이콘 컬럼 추가
-- 사용자가 저금통 생성 시 고른 아이콘(이모지)을 저장한다.
-- nullable: 기존 저금통(V2 시드 등)은 icon 없이도 유지되며,
--           프론트에서 icon이 NULL이면 이름 기반 아이콘으로 폴백한다.
-- ============================================================

ALTER TABLE piggy_banks
    ADD COLUMN icon VARCHAR(20) NULL COMMENT '저금통 대표 아이콘(이모지)' AFTER name;